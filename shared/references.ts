export function referencesForCheck(checkId: string): ReferenceEntry[] {
  return references.filter((entry) => entry.checkIds.some((id) => id === checkId))
}

export function referencesForProjectFinding(id: string): ReferenceEntry[] {
  return references.filter((entry) => entry.projectCheckIds?.includes(id))
}
export function referencesForManualItem(id: string): ReferenceEntry[] {
  return references.filter((entry) => entry.manualItemIds?.some((itemId) => itemId === id))
}
export function matchesReferenceTarget(entry: ReferenceEntry, target?: ReferenceTarget): boolean {
  return (
    !target ||
    (target.scope === 'source'
      ? entry.id === target.id
      : target.scope === 'environment'
        ? entry.checkIds.some((id) => id === target.id)
        : target.scope === 'manual'
          ? Boolean(entry.manualItemIds?.some((id) => id === target.id))
          : Boolean(entry.projectCheckIds?.includes(target.id)))
  )
}

/** Copy a source with its interpretation so citations retain the local tool's boundaries. */
export function referenceMarkdown(entries: readonly ReferenceEntry[]): string {
  return entries
    .map((entry) =>
      [
        `### ${entry.title}`,
        `${entry.publisher} · ${referenceKindLabels[entry.kind]} · 核对于 ${entry.checkedAt}`,
        entry.url,
        `摘要：${entry.takeaway}`,
        `在工具中的用途：${entry.application}`,
        `判断边界：${entry.boundary}`,
      ].join('\n\n'),
    )
    .join('\n\n---\n\n')
}
